"""Draws the FabriC++ mark, "F++(TM)", from Arial Regular outlines and writes every vector copy of it.

    pip install fonttools
    python tools/brand-icon.py            # SVGs and Android vectors
    node tools/brand-pngs.js              # PNG sizes for the web app, PWA and desktop

Ink #111820 on white, the same as the earlier "F" mark. The pluses are set close, as "C++" usually
is, and the trademark sign is drawn smaller, hanging from the cap height. The F and pluses are
centred in the 108-unit Android adaptive-icon box and the whole mark stays inside its 66-unit safe
circle, so launcher masks never clip it.
"""
import os, sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
FONT = os.environ.get('ARIAL', 'C:/Windows/Fonts/arial.ttf' if os.name == 'nt' else '/usr/share/fonts/truetype/msttcorefonts/Arial.ttf')
INK = '#111820'
WIDTH = 58  # width of the whole mark in the 108-unit box

f = TTFont(FONT); gs = f.getGlyphSet(); cmap = f.getBestCmap(); hm = f['hmtx']
CAP = 1466  # Arial cap height, font units
# (character, scale, gap after it in font units)
SEQ = [('F', 1, -60), ('+', 1, -150), ('+', 1, -170), ('\u2122', 0.62, 0)]

items = []; x = 0
for ch, k, gap in SEQ:
    g = cmap[ord(ch)]
    bp = BoundsPen(gs); gs[g].draw(bp); gx0, _, gx1, gy1 = bp.bounds
    if k == 1:
        items.append((g, k, x, 0)); x += hm[g][0] + gap
    else:  # small glyph: left edge at x, top on the cap line
        items.append((g, k, x - gx0 * k, CAP - gy1 * k)); x += (gx1 - gx0) * k + gap

def draw(pen, s=1, tx=0, ty=0):
    for g, k, ox, dy in items:
        gs[g].draw(TransformPen(pen, (s * k, 0, 0, -s * k, ox * s + tx, -dy * s + ty)))

bp = BoundsPen(gs); draw(bp)
x0, _, x1, _ = bp.bounds
s = WIDTH / (x1 - x0)
pen = SVGPathPen(gs, lambda v: f'{v:.2f}'.rstrip('0').rstrip('.'))
draw(pen, s, 54 - (x0 + x1) / 2 * s, 54 + CAP / 2 * s)
d = pen.getCommands()

def write(rel, text):
    with open(os.path.join(ROOT, rel), 'w', encoding='utf-8', newline='\n') as fh: fh.write(text)
    print('wrote', rel)

write('public/brand/fabric-icon.svg', f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72"><rect x="18" y="18" width="72" height="72" fill="#ffffff"/><path fill="{INK}" d="{d}"/></svg>\n')
write('public/brand/fabric-mark.svg', f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108"><path fill="{INK}" d="{d}"/></svg>\n')
vec = f'''<vector android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
            <path android:fillColor="{INK}" android:pathData="{d}" />
        </vector>'''
write('android/res/drawable/icon.xml', f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Infinitum launcher icon (FabriC++): ink "F++(TM)" in Arial Regular on white. Generated by tools/brand-icon.py. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background><color android:color="#FFFFFFFF" /></background>
    <foreground>
        {vec}
    </foreground>
    <monochrome>
        {vec}
    </monochrome>
</adaptive-icon>
''')
write('android-native/app/src/main/res/drawable/ic_launcher_foreground.xml', f'''<?xml version="1.0" encoding="utf-8"?>
<!-- FabriC++ mark, "F++(TM)". Generated by tools/brand-icon.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:fillColor="{INK}"
        android:pathData="{d}" />
</vector>
''')
